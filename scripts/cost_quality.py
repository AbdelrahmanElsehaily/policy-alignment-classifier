"""Cost against quality for every model run with prompt v3, from the committed runs.

    uv run python scripts/cost_quality.py   # prints the table, writes results/cost_quality.md

Accuracy is per run (a model's three runs on test are shown as a range). Cost is the mean tokens
per event at the provider's list price, without prompt caching (OpenRouter didn't cache these
calls); latency is the model call alone, as measured on the run.
"""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "cost_quality.md"
PROMPT = "classifier_v3"
SPLITS = ("test", "agents", "agents-pressure", "stress")

# List prices, $ per million tokens (input, output), OpenRouter, 12 Oct 2026. MiniMax-M3 ran on
# MiniMax's own API; its OpenRouter price is used so the models compare on one price list.
PRICES = {
    "MiniMax-M3": (0.30, 1.20),
    "anthropic/claude-haiku-5.5": (0.10, 0.50),
    "anthropic/claude-sonnet-5.5": (2.00, 10.00),
    "anthropic/claude-opus-5.5": (4.00, 20.00),
}


def runs() -> dict[str, dict[str, list[dict[str, float]]]]:
    """model -> split -> one summary per repeat."""
    out: dict[str, dict[str, list[dict[str, float]]]] = defaultdict(lambda: defaultdict(list))
    for path in sorted(RUNS.glob("*/config.json")):
        config = json.loads(path.read_text())
        if not str(config.get("prompt_version") or "").startswith(PROMPT):
            continue
        if config["split"] not in SPLITS or config.get("with_history"):
            continue
        rows = [json.loads(line) for line in (path.parent / "predictions.jsonl").open()]
        model = rows[0]["result"]["model"]
        if model not in PRICES:
            continue
        by_repeat: dict[int, list[dict[str, object]]] = defaultdict(list)
        for row in rows:
            by_repeat[int(row["repeat"])].append(row)
        price_in, price_out = PRICES[model]
        for repeat in by_repeat.values():
            usage = [r["result"]["usage"] for r in repeat]  # type: ignore[index]
            tokens_in = statistics.mean(
                u["input_tokens"] + u["cache_read_input_tokens"] for u in usage
            )
            tokens_out = statistics.mean(u["output_tokens"] for u in usage)
            latency = statistics.median(r["result"]["model_latency_ms"] for r in repeat)  # type: ignore[index]
            correct = sum(r["result"]["decision"]["verdict"] == r["gold"] for r in repeat)  # type: ignore[index]
            out[model][config["split"]].append(
                {
                    "accuracy": correct / len(repeat),
                    "usd_per_1k": (tokens_in * price_in + tokens_out * price_out) / 1000,
                    "latency_s": latency / 1000,
                }
            )
    return out


def span(values: list[float]) -> str:
    low, high = min(values), max(values)
    return f"{low:.0%}" if round(low, 2) == round(high, 2) else f"{low:.0%}–{high:.0%}"


def table() -> str:
    data = runs()
    lines = [
        "| Model (prompt v3) | " + " | ".join(SPLITS) + " | $ per 1,000 events | Median latency |",
        "|---|" + "---|" * len(SPLITS) + "---|---|",
    ]
    for model in sorted(data, key=lambda m: PRICES[m][0]):
        cells = []
        for split in SPLITS:
            reps = data[model].get(split, [])
            if not reps:
                cells.append("")
                continue
            note = f" ({len(reps)} runs)" if len(reps) > 1 else ""
            cells.append(span([r["accuracy"] for r in reps]) + note)
        every = [r for reps in data[model].values() for r in reps]
        usd = statistics.mean(r["usd_per_1k"] for r in every)
        latency = statistics.median(r["latency_s"] for r in every)
        lines.append(f"| {model} | " + " | ".join(cells) + f" | ${usd:.2f} | {latency:.1f} s |")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = table()
    OUT.write_text(
        "# Cost against quality\n\nGenerated by `scripts/cost_quality.py` from `results/runs/`. "
        "Accuracy is 3-way, per run; cost at list price without prompt caching.\n\n" + text,
        encoding="utf-8",
    )
    print(text, end="")


if __name__ == "__main__":
    main()
