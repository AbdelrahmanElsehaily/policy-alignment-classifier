"""What length does to the verdict: the long-context runs, by length, position and needle.

    uv run python scripts/long_context.py      # prints the tables, writes results/long_context.md

Each run on the long-context split is one model, judging every event whole or in parts
(``max_event_chars`` in its config). Accuracy counts a failed call as wrong, since a guardrail
holds it either way.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "long_context.md"
LENGTHS = ("1k", "8k", "32k")
POSITIONS = ("start", "middle", "end")
PRICES = {
    "MiniMax-M3": (0.30, 1.20),
    "minimax/minimax-m3": (0.30, 1.20),
    "anthropic/claude-haiku-5.5": (0.10, 0.50),
}


def _tag(tags: list[str], prefix: str) -> str:
    return next(t.split(":", 1)[1] for t in tags if t.startswith(prefix + ":"))


def _pct(rows: list[dict[str, object]]) -> str:
    if not rows:
        return ""
    right = sum(r["verdict"] == r["gold"] for r in rows)
    return f"{right / len(rows):.0%} ({right}/{len(rows)})"


def load() -> dict[str, list[dict[str, object]]]:
    runs: dict[str, list[dict[str, object]]] = {}
    for config_path in sorted(RUNS.glob("*/config.json")):
        config = json.loads(config_path.read_text())
        if config["split"] != "long-context":
            continue
        mode = (
            f"parts of {config['max_event_chars']:,} chars"
            if config.get("max_event_chars")
            else "whole"
        )
        rows = []
        for line in (config_path.parent / "predictions.jsonl").open():
            p = json.loads(line)
            r = p["result"]
            rows.append(
                {
                    "model": r["model"],
                    "verdict": r["decision"]["verdict"],
                    "gold": p["gold"],
                    "error": r["error"],
                    "length": _tag(p["tags"], "len"),
                    "position": _tag(p["tags"], "pos"),
                    "needle": _tag(p["tags"], "needle"),
                    "tokens_in": r["usage"]["input_tokens"] + r["usage"]["cache_read_input_tokens"],
                    "tokens_out": r["usage"]["output_tokens"],
                    "latency_s": r["model_latency_ms"] / 1000,
                }
            )
        runs[f"{rows[0]['model']}, {mode}"] = rows
    return runs


def report() -> str:
    runs = load()
    out = ["## Accuracy by length and position\n"]
    head = "| Run | " + " | ".join(f"{n} tokens" for n in LENGTHS) + " | " + " | ".join(POSITIONS)
    out += [head + " | Failed calls |", "|---" * (len(LENGTHS) + len(POSITIONS) + 2) + "|"]
    for name, rows in runs.items():
        by_len = [_pct([r for r in rows if r["length"] == n]) for n in LENGTHS]
        by_pos = [_pct([r for r in rows if r["position"] == p]) for p in POSITIONS]
        failed = sum(r["error"] is not None for r in rows)
        out.append(f"| {name} | " + " | ".join(by_len + by_pos) + f" | {failed} |")

    out += ["\n## Violations caught, by needle and length\n"]
    needles = sorted({str(r["needle"]) for rows in runs.values() for r in rows})
    out += ["| Run | Needle | " + " | ".join(LENGTHS) + " | Harmless twins allowed |"]
    out += ["|---" * (len(LENGTHS) + 3) + "|"]
    for name, rows in runs.items():
        for needle in needles:
            mine = [r for r in rows if r["needle"] == needle]
            caught = [
                _pct([r for r in mine if r["gold"] == "violation" and r["length"] == n])
                for n in LENGTHS
            ]
            twins = _pct([r for r in mine if r["gold"] == "allow"])
            out.append(f"| {name} | {needle} | " + " | ".join(caught) + f" | {twins} |")

    out += ["\n## Cost and latency by length\n"]
    out += [
        "| Run | " + " | ".join(f"{n}: tokens in, $/1k events, median s" for n in LENGTHS) + " |"
    ]
    out += ["|---" * (len(LENGTHS) + 1) + "|"]
    for name, rows in runs.items():
        cells = []
        price_in, price_out = PRICES.get(str(rows[0]["model"]), (0.0, 0.0))
        for n in LENGTHS:
            mine = [r for r in rows if r["length"] == n]
            tin = statistics.mean(float(r["tokens_in"]) for r in mine)  # type: ignore[arg-type]
            tout = statistics.mean(float(r["tokens_out"]) for r in mine)  # type: ignore[arg-type]
            usd = (tin * price_in + tout * price_out) / 1000
            lat = statistics.median(float(r["latency_s"]) for r in mine)  # type: ignore[arg-type]
            cells.append(f"{tin:,.0f}, ${usd:.2f}, {lat:.1f} s")
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def main() -> None:
    text = report()
    OUT.write_text(
        "# Long context\n\nGenerated by `scripts/long_context.py` from the runs on the "
        "long-context split (`data/eval/long_context.jsonl`).\n\n" + text,
        encoding="utf-8",
    )
    print(text, end="")


if __name__ == "__main__":
    main()
